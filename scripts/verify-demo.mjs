import { createRequire } from 'node:module'
import assert from 'node:assert/strict'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
const require = createRequire(new URL('../apps/web/package.json', import.meta.url))
const { chromium } = require('@playwright/test')
const cache = path.join(os.homedir(), '.cache/ms-playwright')
const installed = fs.existsSync(cache) ? fs.readdirSync(cache).filter(n => n.startsWith('chromium-')).sort().reverse().map(n => path.join(cache, n, 'chrome-linux64/chrome')).find(p => fs.existsSync(p)) : undefined
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || installed, args: ['--no-sandbox'] })
const base = process.env.DEMO_URL || 'http://localhost:5173'
fs.mkdirSync('artifacts', { recursive: true })
const { expect } = require('@playwright/test')
const context = await browser.newContext({ viewport: { width: 1600, height: 1000 }, colorScheme: 'dark' })
const page = await context.newPage()
const errors = []
page.on('pageerror', e => errors.push(e.message))
const retired = ['/analytics', '/activity', '/reports', '/prompts', '/teams', '/workflows', '/claude-home', '/plugins', '/memory', '/monitor', '/chat', '/insights']
try {
  await page.goto(base, { waitUntil: 'networkidle' })
  const main = page.locator('main')
  await expect(page.locator('[data-session-id]')).toHaveCount(12)
  await expect(page.locator('.runtime-glyph')).toHaveCount(5)
  for (const glyph of ['.runtime-term-c', '.runtime-dot', '.runtime-line']) {
    await expect(page.locator('.runtime-glyph').filter({ has: page.locator(glyph) }).first()).toBeVisible()
  }
  const runningActivity = page.locator('[data-session-id="demo-session-004"] .session-runtime-activity')
  const initialActivity = await runningActivity.textContent()
  await expect.poll(() => runningActivity.textContent(), { timeout: 6000 }).not.toBe(initialActivity)
  const navigation = page.getByRole('navigation', { name: 'Main navigation', exact: true })
  await expect(navigation.getByRole('link')).toHaveCount(2)
  for (const label of ['Grid view', 'Board view', 'Monitor view', 'Harness view', 'New CLI session']) {
    await expect(main.getByRole('button', { name: label, exact: true })).toHaveCount(0)
  }
  await expect(main).not.toContainText('Today:')
  await expect(main).not.toContainText('$')
  await expect(page.getByRole('button', { name: 'Sign in' })).toHaveCount(0)
  const before = await page.evaluate(async () => (await (await fetch('/api/live/sessions')).json()).sessions.reduce((n, s) => n + s.tokens.totalTokens, 0))
  await expect.poll(async () => page.evaluate(async () => (await (await fetch('/api/live/sessions')).json()).sessions.reduce((n, s) => n + s.tokens.totalTokens, 0)), { timeout: 10000 }).toBeGreaterThan(before)
  await page.screenshot({ path: 'artifacts/dashboard-board-dark.png' })
  assert(await main.locator('.session-title, .session-last-prompt').evaluateAll(nodes => nodes.every(n => Array.from(n.textContent.replace(/^→/, '')).length <= 50)))

  const originalOrder = await page.locator('[data-session-id]').evaluateAll(nodes => nodes.map(n => n.dataset.sessionId))
  await expect.poll(async () => page.evaluate(async () => (await (await fetch('/api/live/sessions')).json()).sessions.reduce((n, s) => n + s.tokens.totalTokens, 0)), { timeout: 10000 }).toBeGreaterThan(before)
  assert.deepEqual(await page.locator('[data-session-id]').evaluateAll(nodes => nodes.map(n => n.dataset.sessionId)), originalOrder, 'Tool/activity updates must not reorder the prompt timeline')
  assert.equal(await page.locator('.session-grid').evaluate(el => getComputedStyle(el).gridTemplateColumns.split(' ').length), 4)

  // Search and project filters still operate on the board.
  await main.getByRole('button', { name: 'Filters', exact: true }).click()
  const filters = page.getByRole('dialog', { name: 'Board filters' })
  const search = filters.getByRole('textbox', { name: 'Search sessions', exact: true })
  await search.fill('OAuth')
  await expect(page.locator('[data-session-id]')).toHaveCount(3)
  await search.fill('no-such-task')
  await expect(page.locator('[data-session-id]')).toHaveCount(0)
  await search.fill('')
  await expect(page.locator('[data-session-id]')).toHaveCount(12)
  await filters.getByRole('checkbox', { name: 'agentHUD', exact: true }).click()
  await expect(filters.getByRole('checkbox', { name: 'agentHUD', exact: true })).toBeChecked()
  await expect.poll(async () => page.locator('[data-session-id]').count()).toBeLessThan(12)
  assert((await page.locator('[data-session-id]').count()) > 0)
  await filters.getByRole('button', { name: 'Clear filters' }).click()
  await expect(page.locator('[data-session-id]')).toHaveCount(12)

  await filters.getByRole('checkbox', { name: 'idle', exact: true }).click()
  await expect(filters.getByRole('checkbox', { name: 'idle', exact: true })).toBeChecked()
  await expect(page.locator('[data-session-id]')).toHaveCount(4)
  await expect(page.locator('.task-card')).toHaveCount(4)
  await filters.getByRole('button', { name: 'Close filters' }).click()
  const needYou = main.getByRole('button', { name: 'Need you', exact: true })
  await needYou.click()
  await expect(needYou).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('[data-session-id]')).toHaveCount(3)
  assert(await page.locator('[data-session-id]').evaluateAll(nodes => nodes.every(n => n.dataset.sessionStatus === 'needs_you')))
  await needYou.click()
  await expect(needYou).toHaveAttribute('aria-pressed', 'false')
  await expect(page.locator('[data-session-id]')).toHaveCount(4)
  await main.getByRole('button', { name: 'Filters', exact: true }).click()
  await expect(filters.getByRole('checkbox', { name: 'idle', exact: true })).toBeChecked()
  await filters.getByRole('button', { name: 'Clear filters' }).click()
  await filters.getByRole('button', { name: 'Close filters' }).click()
  await expect(main.getByRole('heading', { name: 'Task board' })).toHaveCount(0)
  await expect(main.locator('.task-card time')).toHaveCount(12)
  assert(await main.locator('.task-card time').evaluateAll(nodes => nodes.every(n => /ago$/.test(n.textContent))))

  await page.keyboard.press('/')
  await expect(page.getByRole('textbox', { name: 'Search sessions', exact: true })).toBeFocused()
  await page.getByRole('combobox', { name: 'Group', exact: true }).selectOption('project-branch')
  await expect(page.locator('[data-project-group]')).toHaveCount(4)
  await expect(page.locator('[data-session-id]')).toHaveCount(12)
  assert.equal(new URL(page.url()).searchParams.get('groupBy'), 'project-branch')
  await filters.getByRole('button', { name: 'Clear filters' }).click()
  await expect(page.getByRole('combobox', { name: 'Group', exact: true })).toHaveValue('project-branch')
  await page.screenshot({ path: 'artifacts/dashboard-grouped-dark.png' })
  await page.getByRole('combobox', { name: 'Group', exact: true }).selectOption('none')
  await expect(page.locator('[data-project-group]')).toHaveCount(0)
  await expect(filters.getByRole('checkbox', { name: 'Need you', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Close filters', exact: true }).click()
  await page.keyboard.press('Control+b')
  await expect.poll(async () => page.locator('aside').evaluate(el => Math.round(el.getBoundingClientRect().width))).toBe(56)
  await page.keyboard.press('Control+b')
  await expect.poll(async () => page.locator('aside').evaluate(el => Math.round(el.getBoundingClientRect().width))).toBeGreaterThan(56)

  await page.goto(base + '/?status=autonomous&project=agentHUD&branch=feat%2Fagent-dashboard&q=Build', { waitUntil: 'networkidle' })
  await expect(page.locator('[data-session-id]')).toHaveCount(0)
  await main.getByRole('button', { name: 'Need you', exact: true }).click()
  await expect(page.locator('[data-session-id]')).toHaveCount(1)
  const scoped = new URL(page.url()).searchParams
  assert.equal(scoped.get('status'), 'autonomous')
  assert.equal(scoped.get('project'), 'agentHUD')
  assert.equal(scoped.get('branch'), 'feat/agent-dashboard')
  assert.equal(scoped.get('q'), 'Build')
  await main.getByRole('button', { name: 'Need you', exact: true }).click()
  await expect(page.locator('[data-session-id]')).toHaveCount(0)
  await page.goto(base, { waitUntil: 'networkidle' })

  // The retained details remain available; retired tabs cannot be restored via deep links.
  await page.locator('[data-session-id]').first().click()
  await expect(page.getByRole('button', { name: 'Close detail panel' })).toBeVisible()
  await expect(page.getByRole('tab', { name: 'Overview', exact: true })).toBeVisible()
  await expect(page.getByRole('tab', { name: 'Cost', exact: true })).toHaveCount(0)
  await expect(page.getByRole('tab', { name: 'Teams', exact: true })).toHaveCount(0)
  await expect(page.getByRole('tab', { name: 'CLI', exact: true })).toHaveCount(0)
  await page.getByRole('tab', { name: 'Chat', exact: true }).click()
  await expect(page.getByText('The implementation follows the existing React and TypeScript patterns.', { exact: false }).first()).toBeVisible()
  await page.getByRole('button', { name: 'Close detail panel' }).click()
  await page.keyboard.press('Control+k')
  await expect(page.getByRole('button', { name: 'Grid view', exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Show sessions needing you', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.keyboard.press('2')
  await expect(page.locator('[data-session-id]')).toHaveCount(12)
  console.log('PASS board, live stream, filters, details, command palette, removed shortcuts')

  for (const route of ['/sessions', '/sessions/demo-session-001', '/settings', '/search?q=dashboard']) {
    await page.goto(base + route, { waitUntil: 'networkidle' })
    await expect(page.locator('body')).not.toContainText('Unexpected Application Error!')
    await expect(page.getByRole('button', { name: 'Continue options' })).toHaveCount(0)
    await expect(page.getByRole('button', { name: 'Resume', exact: true })).toHaveCount(0)
    if (route === '/sessions') {
      await expect(page.getByText('Build the agent activity dashboard', { exact: false }).first()).toBeVisible()
      await page.screenshot({ path: 'artifacts/dashboard-sessions-dark.png' })
    }
    if (route === '/sessions/demo-session-001') {
      await expect(page.getByText('The implementation follows the existing React and TypeScript patterns.', { exact: false }).first()).toBeVisible()
      await page.screenshot({ path: 'artifacts/dashboard-detail-dark.png' })
    }
    if (route === '/settings') {
      await expect(page.getByRole('heading', { name: 'Keyboard Shortcuts' })).toBeVisible()
      await expect(page.getByText('Linked Devices', { exact: true })).toHaveCount(0)
    }
    console.log(`PASS ${route}`)
  }
  for (const route of retired) {
    await page.goto(base + route, { waitUntil: 'networkidle' })
    await expect(page).toHaveURL(base + '/')
    await expect(page.locator('[data-session-id]')).toHaveCount(12)
    console.log(`PASS retired ${route}`)
  }
  await page.goto(base + '/?view=monitor&tab=cost&focus=demo-session-001', { waitUntil: 'networkidle' })
  await expect(page.getByRole('tab', { name: 'Overview', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.getByRole('button', { name: 'Close detail panel' }).click()
  await page.setViewportSize({ width: 900, height: 800 })
  await page.screenshot({ path: 'artifacts/dashboard-board-compact-dark.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('aside')).toHaveCount(0)
  await page.getByRole('button', { name: 'Expand sidebar', exact: true }).click()
  await expect(page.locator('aside')).toBeVisible()
  await page.screenshot({ path: 'artifacts/dashboard-sidebar-mobile-dark.png' })
  await page.getByRole('button', { name: 'Collapse sidebar', exact: true }).click()
  await expect(page.locator('aside')).toHaveCount(0)
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile viewport must not overflow')
  assert.equal(await page.locator('.session-grid').evaluate(el => getComputedStyle(el).gridTemplateColumns.split(' ').length), 2)
  assert(await page.locator('.task-card').evaluateAll(nodes => nodes.every(el => el.getBoundingClientRect().right <= window.innerWidth)), 'Mobile cards must fit both columns without horizontal scrolling')
  await page.screenshot({ path: 'artifacts/dashboard-board-mobile-dark.png' })
  await page.getByRole('button', { name: 'Filters', exact: true }).click()
  await expect(page.getByRole('dialog', { name: 'Board filters' })).toBeVisible()
  await page.screenshot({ path: 'artifacts/dashboard-filters-mobile-dark.png' })
  await page.getByRole('combobox', { name: 'Group', exact: true }).selectOption('project-branch')
  await expect(page.locator('[data-project-group]')).toHaveCount(4)
  assert(await page.locator('.session-grid').evaluateAll(nodes => nodes.every(el => getComputedStyle(el).gridTemplateColumns.split(' ').length === 2)))
  await page.getByRole('button', { name: 'Close filters', exact: true }).click()
  await page.screenshot({ path: 'artifacts/dashboard-grouped-mobile-dark.png' })
  await page.locator('[data-session-id]').first().click()
  await expect(page.getByRole('button', { name: 'Close detail panel' })).toBeVisible()
  await expect.poll(async () => page.getByRole('button', { name: 'Close detail panel' }).evaluate(el => el.getBoundingClientRect().right - window.innerWidth)).toBeLessThanOrEqual(0)
  console.log('PASS compact and mobile layouts')

  assert.deepEqual(errors, [], `Browser errors: ${errors.join('; ')}`)
} finally {
  await context.close()
  await browser.close()
}
